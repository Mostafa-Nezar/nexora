import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:file_picker/file_picker.dart';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';
import '../../core/theme/app_colors.dart';
import '../../core/widgets/app_toast.dart';
import '../../core/widgets/native_context_menu_wrapper.dart';

class FileManagerScreen extends StatefulWidget {
  const FileManagerScreen({super.key});

  @override
  State<FileManagerScreen> createState() => _FileManagerScreenState();
}

class _FileManagerScreenState extends State<FileManagerScreen>
    with SingleTickerProviderStateMixin {
  List<PlatformFile> _pickedFiles = [];
  bool _isLoading = false;
  late AnimationController _animController;

  @override
  void initState() {
    super.initState();
    _animController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 400),
    );
    _animController.forward();
  }

  @override
  void dispose() {
    _animController.dispose();
    super.dispose();
  }

  Future<void> _pickFiles({bool multiple = false}) async {
    setState(() => _isLoading = true);
    try {
      final result = await FilePicker.platform.pickFiles(allowMultiple: multiple);
      if (!mounted) return;
      if (result != null && result.files.isNotEmpty) {
        setState(() => _pickedFiles = result.files);
        final count = result.files.length;
        AppToast.success(context, count == 1
            ? 'Selected: ${result.files.first.name}'
            : 'Selected $count files');
      }
    } catch (e) {
      if (mounted) AppToast.error(context, 'Could not pick file: $e');
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  Future<void> _createSampleFile() async {
    try {
      final dir = await getApplicationDocumentsDirectory();
      final file = File(
        '${dir.path}/Nexora_Sample_${DateTime.now().millisecondsSinceEpoch}.txt',
      );
      await file.writeAsString(
        'Nexora — File Manager & Storage\nCreated at: ${DateTime.now()}\n\nSample document generated by Nexora.',
      );
      HapticFeedback.lightImpact();
      if (mounted) {
        AppToast.success(context, 'Sample file created: ${file.path.split('/').last}');
      }
    } catch (e) {
      if (mounted) AppToast.error(context, 'Failed to create file: $e');
    }
  }

  Future<void> _shareFile(PlatformFile file) async {
    final path = file.path;
    if (path == null) {
      if (mounted) AppToast.error(context, 'File has no local path to share.');
      return;
    }
    await Share.shareXFiles([XFile(path)], text: 'Sharing ${file.name}');
  }

  void _removeFile(PlatformFile file) {
    setState(() => _pickedFiles.remove(file));
    HapticFeedback.selectionClick();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: AppBar(
        title: const Text(
          'File Manager & Storage',
          style: TextStyle(color: Colors.white, fontWeight: FontWeight.bold),
        ),
        backgroundColor: AppColors.background,
        elevation: 0,
        surfaceTintColor: Colors.transparent,
      ),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(16, 8, 16, 120),
        children: [
          // ── Storage Actions Card ───────────────────────────────────
          _buildSectionLabel('Storage Actions', Icons.storage_rounded, AppColors.fileAccent),
          const SizedBox(height: 10),
          _buildActionGrid(),
          const SizedBox(height: 24),

          // ── Selected Files ─────────────────────────────────────────
          if (_pickedFiles.isNotEmpty) ...[
            _buildSectionLabel(
              '${_pickedFiles.length} Selected File${_pickedFiles.length > 1 ? 's' : ''}',
              Icons.check_circle_outline_rounded,
              AppColors.fileAccent,
            ),
            const SizedBox(height: 10),
            ..._pickedFiles.asMap().entries.map(
              (entry) => _buildFileCard(entry.value, entry.key),
            ),
          ] else ...[
            _buildEmptyState(),
          ],
        ],
      ),
    );
  }

  Widget _buildSectionLabel(String label, IconData icon, Color color) {
    return Row(
      children: [
        Icon(icon, color: color, size: 18),
        const SizedBox(width: 8),
        Text(
          label,
          style: TextStyle(
            color: color,
            fontWeight: FontWeight.bold,
            fontSize: 14,
            letterSpacing: 0.5,
          ),
        ),
      ],
    );
  }

  Widget _buildActionGrid() {
    return Column(
      children: [
        Row(
          children: [
            Expanded(
              child: _buildActionTile(
                icon: Icons.insert_drive_file_rounded,
                label: 'Pick File',
                sublabel: 'Single select',
                color: AppColors.fileAccent,
                onTap: () => _pickFiles(multiple: false),
              ),
            ),
            const SizedBox(width: 12),
            Expanded(
              child: _buildActionTile(
                icon: Icons.file_copy_rounded,
                label: 'Pick Files',
                sublabel: 'Multi select',
                color: const Color(0xFFE67E22),
                onTap: () => _pickFiles(multiple: true),
              ),
            ),
          ],
        ),
        const SizedBox(height: 12),
        Row(
          children: [
            Expanded(
              child: _buildActionTile(
                icon: Icons.note_add_rounded,
                label: 'Create File',
                sublabel: 'Sample .txt',
                color: AppColors.scannerAccent,
                onTap: _createSampleFile,
              ),
            ),
            const SizedBox(width: 12),
            Expanded(
              child: _buildActionTile(
                icon: Icons.delete_sweep_rounded,
                label: 'Clear All',
                sublabel: 'Remove selection',
                color: Colors.redAccent,
                onTap: _pickedFiles.isEmpty
                    ? null
                    : () {
                        setState(() => _pickedFiles = []);
                        HapticFeedback.heavyImpact();
                      },
              ),
            ),
          ],
        ),
      ],
    );
  }

  Widget _buildActionTile({
    required IconData icon,
    required String label,
    required String sublabel,
    required Color color,
    VoidCallback? onTap,
  }) {
    final disabled = onTap == null;
    return Material(
      color: Colors.transparent,
      child: InkWell(
        onTap: _isLoading ? null : onTap,
        borderRadius: BorderRadius.circular(16),
        splashColor: color.withValues(alpha: 0.15),
        child: Container(
          padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 16),
          decoration: BoxDecoration(
            color: color.withValues(alpha: disabled ? 0.03 : 0.08),
            borderRadius: BorderRadius.circular(16),
            border: Border.all(
              color: color.withValues(alpha: disabled ? 0.1 : 0.3),
              width: 1.2,
            ),
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Container(
                padding: const EdgeInsets.all(8),
                decoration: BoxDecoration(
                  color: color.withValues(alpha: disabled ? 0.05 : 0.15),
                  borderRadius: BorderRadius.circular(10),
                ),
                child: Icon(icon, color: disabled ? Colors.white24 : color, size: 20),
              ),
              const SizedBox(height: 10),
              Text(
                label,
                style: TextStyle(
                  color: disabled ? Colors.white24 : Colors.white,
                  fontWeight: FontWeight.bold,
                  fontSize: 13,
                ),
              ),
              const SizedBox(height: 2),
              Text(
                sublabel,
                style: TextStyle(
                  color: disabled ? Colors.white12 : Colors.white54,
                  fontSize: 11,
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildFileCard(PlatformFile file, int index) {
    final ext = file.extension?.toUpperCase() ?? '?';
    final sizeKb = (file.size / 1024).toStringAsFixed(1);
    final sizeMb = (file.size / (1024 * 1024)).toStringAsFixed(2);
    final displaySize = file.size > 1024 * 1024 ? '$sizeMb MB' : '$sizeKb KB';

    Color extColor = AppColors.fileAccent;
    IconData extIcon = Icons.insert_drive_file_rounded;
    if (['JPG', 'JPEG', 'PNG', 'GIF', 'WEBP'].contains(ext)) {
      extColor = Colors.cyanAccent;
      extIcon = Icons.image_rounded;
    } else if (['MP4', 'MOV', 'AVI', 'MKV'].contains(ext)) {
      extColor = Colors.deepPurpleAccent;
      extIcon = Icons.movie_rounded;
    } else if (['MP3', 'WAV', 'AAC', 'FLAC'].contains(ext)) {
      extColor = AppColors.mediaAccent;
      extIcon = Icons.music_note_rounded;
    } else if (['PDF'].contains(ext)) {
      extColor = Colors.redAccent;
      extIcon = Icons.picture_as_pdf_rounded;
    } else if (['ZIP', 'RAR', '7Z', 'TAR'].contains(ext)) {
      extColor = Colors.orangeAccent;
      extIcon = Icons.folder_zip_rounded;
    } else if (['TXT', 'MD', 'LOG', 'JSON', 'XML', 'CSV'].contains(ext)) {
      extColor = AppColors.scannerAccent;
      extIcon = Icons.description_rounded;
    }

    return NativeContextMenuWrapper(
      title: file.name,
      shareContent: file.path ?? file.name,
      onShare: () => _shareFile(file),
      child: Container(
        margin: const EdgeInsets.only(bottom: 10),
        decoration: BoxDecoration(
          color: AppColors.surface,
          borderRadius: BorderRadius.circular(16),
          border: Border.all(color: extColor.withValues(alpha: 0.2), width: 1),
        ),
        child: Row(
          children: [
            // File type icon block
            Container(
              width: 60,
              height: 70,
              decoration: BoxDecoration(
                color: extColor.withValues(alpha: 0.1),
                borderRadius: const BorderRadius.only(
                  topLeft: Radius.circular(16),
                  bottomLeft: Radius.circular(16),
                ),
              ),
              child: Column(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  Icon(extIcon, color: extColor, size: 22),
                  const SizedBox(height: 4),
                  Text(
                    ext,
                    style: TextStyle(
                      color: extColor,
                      fontSize: 9,
                      fontWeight: FontWeight.bold,
                      letterSpacing: 0.5,
                    ),
                  ),
                ],
              ),
            ),
            // File details
            Expanded(
              child: Padding(
                padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      file.name,
                      style: const TextStyle(
                        color: Colors.white,
                        fontSize: 13,
                        fontWeight: FontWeight.w600,
                      ),
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                    ),
                    const SizedBox(height: 4),
                    Row(
                      children: [
                        Icon(Icons.sd_storage_rounded,
                            color: Colors.white38, size: 12),
                        const SizedBox(width: 4),
                        Text(
                          displaySize,
                          style: const TextStyle(
                              color: Colors.white38, fontSize: 11),
                        ),
                        if (file.path != null) ...[
                          const SizedBox(width: 10),
                          const Icon(Icons.link_rounded,
                              color: Colors.white24, size: 12),
                          const SizedBox(width: 4),
                          Expanded(
                            child: Text(
                              file.path!.replaceFirst(RegExp(r'.*/'), '…/'),
                              style: const TextStyle(
                                  color: Colors.white24, fontSize: 10),
                              maxLines: 1,
                              overflow: TextOverflow.ellipsis,
                            ),
                          ),
                        ],
                      ],
                    ),
                  ],
                ),
              ),
            ),
            // Actions
            Column(
              children: [
                IconButton(
                  icon: const Icon(Icons.share_rounded,
                      color: Colors.white38, size: 18),
                  onPressed: () => _shareFile(file),
                  tooltip: 'Share',
                ),
                IconButton(
                  icon: const Icon(Icons.close_rounded,
                      color: Colors.white24, size: 18),
                  onPressed: () => _removeFile(file),
                  tooltip: 'Remove',
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildEmptyState() {
    return Container(
      margin: const EdgeInsets.only(top: 24),
      padding: const EdgeInsets.symmetric(vertical: 40),
      decoration: BoxDecoration(
        color: AppColors.surface,
        borderRadius: BorderRadius.circular(20),
        border: Border.all(color: Colors.white.withValues(alpha: 0.06)),
      ),
      child: Column(
        children: [
          Container(
            padding: const EdgeInsets.all(20),
            decoration: BoxDecoration(
              color: AppColors.fileAccent.withValues(alpha: 0.08),
              shape: BoxShape.circle,
            ),
            child: Icon(Icons.folder_open_rounded,
                color: AppColors.fileAccent.withValues(alpha: 0.5), size: 40),
          ),
          const SizedBox(height: 16),
          const Text(
            'No files selected yet',
            style: TextStyle(
                color: Colors.white60, fontSize: 16, fontWeight: FontWeight.w600),
          ),
          const SizedBox(height: 6),
          const Text(
            'Pick files or create a sample document\nusing the actions above.',
            style: TextStyle(color: Colors.white38, fontSize: 12, height: 1.5),
            textAlign: TextAlign.center,
          ),
        ],
      ),
    );
  }
}
